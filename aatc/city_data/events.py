"""Annual Korean holidays and sourced local event records for simulation scenarios."""
import json
from datetime import date, datetime, time
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CITY_EVENT_ROOT = ROOT / "config" / "city_events"
PROFILE_PATH = ROOT / "config" / "daily_demand_profiles.json"
PUBLIC_HOLIDAY_SOURCE = "https://www.data.go.kr/data/15012690/openapi.do"


def load_daily_profile():
    with PROFILE_PATH.open("r", encoding="utf-8-sig") as handle:
        return json.load(handle)


def annual_calendar(city, year):
    """Return date-indexed Korea public holidays and locally sourced, date-specific events."""
    city_key = str(city).strip().casefold().replace(" ", "_")
    events = []
    try:
        import holidays
        korea_holidays = holidays.country_holidays("KR", years=[int(year)], observed=True, language="ko")
        for day, name in korea_holidays.items():
            events.append({"event_id": "kr_holiday_{}".format(day.isoformat()), "name": str(name),
                           "category": "national_public_holiday", "start_date": day.isoformat(),
                           "end_date": day.isoformat(), "location": "South Korea",
                           "traffic_impact_assumption": "public_holiday_demand_profile",
                           "impact_is_measured": False, "expected_attendance": None,
                           "confidence": "date generated by holidays package; validate against official calendar",
                           "source_url": PUBLIC_HOLIDAY_SOURCE})
    except ImportError:
        pass
    event_path = CITY_EVENT_ROOT / "{}_{}.json".format(city_key, int(year))
    curated = {}
    if event_path.is_file():
        with event_path.open("r", encoding="utf-8-sig") as handle:
            curated = json.load(handle)
        events.extend(curated.get("events", []))
    return {"city": city, "year": int(year), "events": sorted(events, key=lambda e: e.get("start_date", "")),
            "curated_local_events_available": bool(curated),
            "holiday_source": PUBLIC_HOLIDAY_SOURCE,
            "local_event_source_kind": curated.get("source_kind"),
            "note": "Event traffic impacts are scenario assumptions, not measured traffic counts."}


def scenario_for_datetime(city, target_datetime, event_calendar=None):
    """Select configurable day/time demand assumptions and matching local event signals."""
    if isinstance(target_datetime, str):
        target_datetime = datetime.fromisoformat(target_datetime)
    if not isinstance(target_datetime, datetime):
        raise TypeError("target_datetime must be a datetime or ISO-8601 string")
    calendar = event_calendar or annual_calendar(city, target_datetime.year)
    profile = load_daily_profile()
    period = None
    target_time = target_datetime.time()
    for candidate in profile["periods"]:
        start = time.fromisoformat(candidate["start"])
        end_text = candidate["end"]
        end = time(23, 59, 59) if end_text == "24:00" else time.fromisoformat(end_text)
        if start <= target_time < end or (end_text == "24:00" and target_time >= start):
            period = dict(candidate)
            break
    if period is None:
        raise ValueError("No configured daily traffic period matches the requested time")
    weekday = target_datetime.weekday()
    day_type = "weekday" if weekday < 5 else "saturday" if weekday == 5 else "sunday"
    date_matches = [event for event in calendar.get("events", [])
                    if event.get("start_date", "") <= target_datetime.date().isoformat()
                    <= event.get("end_date", event.get("start_date", ""))]
    matches = []
    for event in date_matches:
        item = dict(event)
        start_text, end_text = item.get("start_time"), item.get("end_time")
        if start_text and end_text:
            active_at_time = time.fromisoformat(start_text) <= target_time <= time.fromisoformat(end_text)
            item["active_at_target_time"] = active_at_time
        elif item.get("category") == "national_public_holiday":
            item["active_at_target_time"] = True
        else:
            # Keep date-level events visible but don't assign a time-specific demand boost
            # when the source did not publish hours.
            item["active_at_target_time"] = False
            item["time_window_status"] = "not provided by source; no local-event multiplier applied"
        matches.append(item)
    public_holiday = any(event.get("category") == "national_public_holiday" for event in matches)
    if public_holiday:
        day_type = "public_holiday"
    multiplier = profile["day_type_multipliers"][day_type] * period["demand_multiplier"]
    local_event_factor = 1.0
    configured_events = profile.get("event_multipliers", {})
    applied_event_ids = []
    for event in matches:
        if not event.get("active_at_target_time"):
            continue
        factor = configured_events.get(event.get("traffic_impact_assumption"), 1.0)
        if period.get("profile") in ("commute_inbound", "commute_outbound"):
            factor = max(1.0, float(factor))
        if factor > 1.0:
            applied_event_ids.append(event.get("event_id"))
        local_event_factor = max(local_event_factor, float(factor))
    return {"city": city, "target_datetime": target_datetime.isoformat(), "day_type": day_type,
            "time_period": period, "day_type_multiplier": profile["day_type_multipliers"][day_type],
            "base_period_multiplier": period["demand_multiplier"],
            "event_multiplier": local_event_factor,
            "combined_relative_demand_multiplier": round(multiplier * local_event_factor, 3),
            "applied_event_ids": applied_event_ids,
            "directional_assumption": profile["directional_assumption"].get(
                period["id"], profile["directional_assumption"]["default"]),
            "active_events": matches,
            "assumption_note": profile["note"]}
